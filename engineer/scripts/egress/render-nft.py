#!/usr/bin/env python3
"""Print the nftables ruleset that confines the listed users to named loopback ports.

Usage: render-nft.py --uid NAME=UID [--uid ...] [--lo NAME=PORT[,PORT...] ...] [--table engineer_egress]

The listed uids may open new connections only to the loopback TCP ports given for them with --lo
(the egress proxy at 127.0.0.1:PROXY_PORT; for engineer also x11vnc, which noVNC's websockify
reaches). Replies on loopback connections that others opened to them (cloudflared to noVNC) pass
as established. DNS (port 53, TCP and UDP) is dropped first, so the local resolver (127.0.0.53)
is no way round the proxy. Any other output of theirs is logged and dropped. Every other uid, root
included, is untouched (the chain policy is accept). The output replaces the table atomically when
loaded with `nft -f`. Bad input exits 2 (argparse).
"""
import argparse
import re
import sys

_NAME = re.compile(r"^[a-z_][a-z0-9_-]{0,31}$")
_TABLE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,63}$")


def _uid(spec: str):
    name, sep, uid = spec.partition("=")
    if not sep or not _NAME.match(name) or not uid.isdigit():
        raise argparse.ArgumentTypeError(f"want NAME=UID, got {spec!r}")
    n = int(uid)
    if n == 0 or n > 4294967294:
        raise argparse.ArgumentTypeError(f"uid out of range (root is never confined): {spec!r}")
    return name, n


def _lo(spec: str):
    name, sep, ports = spec.partition("=")
    if not sep or not _NAME.match(name):
        raise argparse.ArgumentTypeError(f"want NAME=PORT[,PORT...], got {spec!r}")
    out = []
    for p in ports.split(","):
        if not p.isdigit() or not 0 < int(p) < 65536 or int(p) == 53:
            raise argparse.ArgumentTypeError(f"bad loopback port {p!r} in {spec!r} (1-65535, never 53)")
        if int(p) not in out:
            out.append(int(p))
    return name, out


def _table(name: str) -> str:
    if not _TABLE.match(name):
        raise argparse.ArgumentTypeError(f"bad table name: {name!r}")
    return name


def render(uids: list, table: str = "engineer_egress", lo: list = ()) -> str:
    """The ruleset text for uids [(name, uid), ...] and loopback ports lo [(name, [port, ...]), ...]."""
    seen, by_name = [], {}
    for name, n in uids:
        if n not in seen:
            seen.append(n)
        by_name.setdefault(name, n)
    names = ", ".join(by_name)
    skuid = "meta skuid { " + ", ".join(str(n) for n in seen) + " }"
    ports = {}
    for name, plist in lo:
        for p in plist:
            if p not in ports.setdefault(by_name[name], []):
                ports[by_name[name]].append(p)
    port_rules = [f'    meta skuid {n} oif "lo" tcp dport {{ {", ".join(map(str, ports[n]))} }} accept'
                  for n in seen if ports.get(n)]
    return "\n".join([
        "#!/usr/sbin/nft -f",
        f"# Engineer egress: {names} reach only named loopback ports (the proxy); generated by render-nft.py.",
        f"table inet {table}",
        f"delete table inet {table}",
        f"table inet {table} {{",
        "  chain output {",
        "    type filter hook output priority 0; policy accept;",
        f'    {skuid} meta l4proto {{ tcp, udp }} th dport 53 log prefix "engineer-egress-dns " drop',
        f'    {skuid} oif "lo" ct state established,related accept',
        *port_rules,
        f'    {skuid} log prefix "engineer-egress-drop " drop',
        "  }",
        "}",
        "",
    ])


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="Render the engineer egress nftables ruleset.")
    p.add_argument("--uid", action="append", type=_uid, required=True, metavar="NAME=UID")
    p.add_argument("--lo", action="append", type=_lo, default=[], metavar="NAME=PORT[,PORT...]")
    p.add_argument("--table", type=_table, default="engineer_egress")
    args = p.parse_args(argv)
    unknown = {name for name, _ in args.lo} - {name for name, _ in args.uid}
    if unknown:
        p.error(f"--lo names a user not given with --uid: {', '.join(sorted(unknown))}")
    sys.stdout.write(render(args.uid, args.table, args.lo))
    return 0


if __name__ == "__main__":
    sys.exit(main())
