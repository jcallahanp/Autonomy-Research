#!/usr/bin/env python3
"""Print the nftables ruleset that confines the listed users to loopback.

Usage: render-nft.py --uid NAME=UID [--uid NAME=UID ...] [--table engineer_egress]

The listed uids may send only on the loopback interface, where the egress proxy listens
(127.0.0.1:PROXY_PORT); any other output of theirs is logged and dropped. Every other uid,
root included, is untouched (the chain policy is accept). The output replaces the table
atomically when loaded with `nft -f`. Bad input exits 2 (argparse).
"""
import argparse
import re
import sys

_NAME = re.compile(r"^[a-z_][a-z0-9_-]{0,31}$")
_TABLE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,63}$")


def _uid(spec: str):
    name, sep, uid = spec.partition("=")
    if not sep or not _NAME.match(name) or not uid.isdigit():
        raise argparse.ArgumentTypeError(f"want NAME=UID, got {spec!r}")
    n = int(uid)
    if n == 0 or n > 4294967294:
        raise argparse.ArgumentTypeError(f"uid out of range (root is never confined): {spec!r}")
    return name, n


def _table(name: str) -> str:
    if not _TABLE.match(name):
        raise argparse.ArgumentTypeError(f"bad table name: {name!r}")
    return name


def render(uids: list, table: str = "engineer_egress") -> str:
    """The ruleset text for [(name, uid), ...]."""
    seen = []
    for _, n in uids:
        if n not in seen:
            seen.append(n)
    names = ", ".join(dict.fromkeys(name for name, _ in uids))
    skuid = "meta skuid { " + ", ".join(str(n) for n in seen) + " }"
    return "\n".join([
        "#!/usr/sbin/nft -f",
        f"# Engineer egress: {names} reach only loopback (the proxy); generated by render-nft.py.",
        f"table inet {table}",
        f"delete table inet {table}",
        f"table inet {table} {{",
        "  chain output {",
        "    type filter hook output priority 0; policy accept;",
        f'    {skuid} oif "lo" accept',
        f'    {skuid} log prefix "engineer-egress-drop " drop',
        "  }",
        "}",
        "",
    ])


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="Render the engineer egress nftables ruleset.")
    p.add_argument("--uid", action="append", type=_uid, required=True, metavar="NAME=UID")
    p.add_argument("--table", type=_table, default="engineer_egress")
    args = p.parse_args(argv)
    sys.stdout.write(render(args.uid, args.table))
    return 0


if __name__ == "__main__":
    sys.exit(main())
